/**
 * Get task type prompt
 */
export function getTaskTypePrompt(type: TaskType): string {
  return TASK_TYPE_PROMPTS[type] || TASK_TYPE_PROMPTS.custom
}

/**
 * Get priority context
 */
export function getPriorityContext(priority: TaskPriority): string {
  return PRIORITY_CONTEXT[priority] || PRIORITY_CONTEXT.normal
}

/**
 * Get output format template
 */
export function getOutputFormat(format: keyof typeof OUTPUT_FORMATS): string {
  return OUTPUT_FORMATS[format] || ''
}

/**
 * Get collaboration prompt
 */
export function getCollaborationPrompt(type: keyof typeof COLLABORATION_PROMPTS): string {
  return COLLABORATION_PROMPTS[type] || ''
}
